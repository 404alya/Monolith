#!/usr/bin/env python3
"""Turn TrueType fonts into a C header that the editor compiles in (src/font_outfit.h).

    python3 -I tools/embed_font.py src/font_outfit.h \
        OUTFIT_REGULAR=resources/fonts/outfit/Outfit-Regular.ttf \
        OUTFIT_SEMIBOLD=resources/fonts/outfit/Outfit-SemiBold.ttf

For each NAME=file the header gets the file's bytes (NAME, NAME_SIZE) and the codepoints the
font has a glyph for, in ascending order, out of ASCII, Latin-1 and Latin Extended-A
(NAME_CODEPOINTS, NAME_CODEPOINT_COUNT). Ascending order keeps ASCII at the start of the
font's glyph table, where raylib's linear GetGlyphIndex finds it first. Standard library
only: the cmap is read here (formats 4 and 12), the font is never run or rendered.
"""
import hashlib
import os
import struct
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0x17F)]   # ASCII, Latin-1 Supplement, Latin Extended-A


def cmap_codepoints(data):
    """Every codepoint the font's Unicode cmap maps to a glyph other than .notdef."""
    num_tables = struct.unpack_from(">H", data, 4)[0]
    cmap = None
    for i in range(num_tables):
        tag, _, offset, _ = struct.unpack_from(">4sIII", data, 12 + 16 * i)
        if tag == b"cmap":
            cmap = offset
    if cmap is None:
        raise ValueError("no cmap table")
    best = None
    for i in range(struct.unpack_from(">H", data, cmap + 2)[0]):
        platform, encoding, offset = struct.unpack_from(">HHI", data, cmap + 4 + 8 * i)
        fmt = struct.unpack_from(">H", data, cmap + offset)[0]
        unicode = platform == 0 or (platform == 3 and encoding in (1, 10))
        if unicode and fmt in (4, 12) and (best is None or fmt > best[0]):
            best = (fmt, cmap + offset)
    if best is None:
        raise ValueError("no Unicode cmap subtable of format 4 or 12")
    fmt, sub = best
    found = set()
    if fmt == 12:
        groups = struct.unpack_from(">I", data, sub + 12)[0]
        for g in range(groups):
            start, end, glyph = struct.unpack_from(">III", data, sub + 16 + 12 * g)
            found.update(c for c in range(start, end + 1) if glyph + c - start)
        return found
    segs = struct.unpack_from(">H", data, sub + 6)[0] // 2
    ends = sub + 14
    starts = ends + 2 * segs + 2
    deltas = starts + 2 * segs
    ranges = deltas + 2 * segs
    for s in range(segs):
        end, start = struct.unpack_from(">H", data, ends + 2 * s)[0], struct.unpack_from(">H", data, starts + 2 * s)[0]
        delta, ro = struct.unpack_from(">h", data, deltas + 2 * s)[0], struct.unpack_from(">H", data, ranges + 2 * s)[0]
        for c in range(start, min(end, 0xFFFE) + 1):
            if ro == 0:
                glyph = (c + delta) & 0xFFFF
            else:
                glyph = struct.unpack_from(">H", data, ranges + 2 * s + ro + 2 * (c - start))[0]
                if glyph:
                    glyph = (glyph + delta) & 0xFFFF
            if glyph:
                found.add(c)
    return found


def main(argv):
    if len(argv) < 3 or any("=" not in a for a in argv[2:]):
        sys.exit(__doc__)
    out = argv[1]
    lines = [
        "// Generated by tools/embed_font.py: do not edit. Regenerate with the command in that file.",
        "// The fonts' licence (SIL Open Font License 1.1) and provenance: resources/fonts/.",
        "#pragma once",
        "",
    ]
    for arg in argv[2:]:
        name, path = arg.split("=", 1)
        with open(path, "rb") as f:
            data = f.read()
        have = cmap_codepoints(data)
        cps = [c for lo, hi in RANGES for c in range(lo, hi + 1) if c in have]
        if ord("?") not in have:
            raise SystemExit(f"{path}: no '?' glyph (raylib's fallback for missing glyphs)")
        lines.append(f"// {os.path.basename(path)}, sha256 {hashlib.sha256(data).hexdigest()}, "
                     f"{len(cps)} codepoints")
        lines.append(f"#define {name}_SIZE {len(data)}")
        lines.append(f"static const unsigned char {name}[{name}_SIZE] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"#define {name}_CODEPOINT_COUNT {len(cps)}")
        lines.append(f"static const int {name}_CODEPOINTS[{name}_CODEPOINT_COUNT] = {{")
        for i in range(0, len(cps), 16):
            lines.append("    " + ", ".join(f"0x{c:03X}" for c in cps[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"embed_font: wrote {out}")


if __name__ == "__main__":
    main(sys.argv)
